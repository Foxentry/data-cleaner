"""
Static country reference data.

This module is GENERATED - do not edit by hand. Reproduce it with:

    pip install phonenumbers Babel
    python tools/update_countries.py --oas <path to a checkout of github.com/Foxentry/OAS>

The generator is deterministic: same inputs, same bytes. `--check` verifies that this file
is up to date without writing anything, which is what CI runs.

The data is baked into the build on purpose: the application must never reach out
to the network at runtime except for the validation calls the user explicitly starts.
Sources: the Foxentry OpenAPI specification (per-service `dataSource` defaults),
ITU-T E.164 calling codes and their primary countries (via `phonenumbers`), and CLDR country
names (via `Babel`). Postal-code shapes, legal-form suffixes and neighbouring countries are
curated in the generator.

Contents
--------
COVERAGE          which countries each Foxentry service supports
CALLING_CODES     ISO 3166-1 alpha-2 -> E.164 calling code
PREFIX_TO_COUNTRY calling code -> the country we treat as primary for detection
NAMES_EN/NAMES_CS country names (English is the default; Czech is a translation)
ZIP_PATTERNS      postal-code shape per country (used to detect the country from data)
COMPANY_SUFFIXES  legal-form suffixes per country (weak detection signal)
NEIGHBOURS        neighbouring countries (used when ranking phone prefixes)
"""

from __future__ import annotations

