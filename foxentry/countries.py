WORLDWIDE = "worldwide"

# --- Service coverage -------------------------------------------------------
# Mirrors the `dataSource` defaults in the Foxentry OpenAPI specification.
# Sending a country a service does not cover only burns credits and returns
# "invalid" for every row, so the wizard warns the user up front.
COVERAGE: dict[str, list[str] | str] = {
    'email': WORLDWIDE,
    'phone': WORLDWIDE,
    'name': ['CZ', 'SK'],
    'company': ['CZ', 'HU', 'PL', 'SK'],
    'location': ['AD', 'AL', 'AT', 'BA', 'BE', 'BG', 'CH', 'CY', 'CZ', 'DE', 'DK', 'ES', 'FR', 'GB', 'GR', 'HR', 'HU', 'IS', 'IT', 'LI', 'LU', 'MC', 'ME', 'MK', 'MT', 'NL', 'PL', 'RO', 'RS', 'SI', 'SK', 'SM', 'VA', 'XK'],
}

# Whether an uncovered country fails hard (a register) or merely degrades
# (reference data such as names).
STRICT_COVERAGE: dict[str, bool] = {
    'location': True,
    'company': True,
    'name': False,
}

def is_strict(service: str) -> bool:
    return STRICT_COVERAGE.get(service, True)


def supports(service: str, country: str | None) -> bool:
    """True when the service can validate data from that country."""
    cov = COVERAGE.get(service, WORLDWIDE)
    if cov == WORLDWIDE:
        return True
    if not country:
        return True  # no country chosen -> the API searches every source
    return country.upper() in cov


def covered_countries(service: str) -> list[str]:
    """The countries a service covers ([] means worldwide)."""
    cov = COVERAGE.get(service, WORLDWIDE)
    return [] if cov == WORLDWIDE else list(cov)


# --- Names ------------------------------------------------------------------
def name(code: str, lang: str = "en") -> str:
    """Country name in the requested language; English is the fallback."""
    code = (code or "").upper()
    if lang == "cs":
        return NAMES_CS.get(code) or NAMES_EN.get(code) or code
    return NAMES_EN.get(code) or code


def flag(code: str) -> str:
    """Regional-indicator flag emoji for an alpha-2 code."""
    code = (code or "").upper()
    if not re.fullmatch(r"[A-Z]{2}", code):
        return ""
    return "".join(chr(0x1F1E6 + ord(ch) - 65) for ch in code)


# --- Phone prefixes ---------------------------------------------------------
def prefix_of(country: str | None) -> str | None:
    """E.164 calling code for a country, e.g. "CZ" -> "+420"."""
    return CALLING_CODES.get((country or "").upper())


def country_of_prefix(number: str) -> str | None:
    """
    Country for a phone number written with an international prefix.
    Longest match wins, so "+420" beats "+42".
    """
    value = re.sub(r"[^\d+]", "", number or "")
    if not value.startswith("+"):
        return None
    for length in range(5, 1, -1):
        hit = PREFIX_TO_COUNTRY.get(value[:length])
        if hit:
            return hit
    return None


def prefix_order(country: str | None) -> list[str]:
    """
    Preferred prefixes for the API, most likely first.

    Only used for numbers written WITHOUT a prefix: the API picks the first
    prefix from this list that makes the number valid.
    """
    order: list[str] = []
    own = prefix_of(country)
    if own:
        order.append(own)
    for neighbour in NEIGHBOURS.get((country or "").upper(), ()):
        pfx = prefix_of(neighbour)
        if pfx and pfx not in order:
            order.append(pfx)
    return order


# --- Postal codes -----------------------------------------------------------
def zip_matches(country: str, value: str) -> bool:
    """True when the value has the shape of that country's postal code."""
    pattern = ZIP_PATTERNS.get((country or "").upper())
    if not pattern or not value:
        return False
    return bool(re.fullmatch(pattern, value.strip(), re.IGNORECASE))


def countries_matching_zip(value: str) -> list[str]:
    """Every country whose postal-code shape the value fits."""
    value = (value or "").strip()
    if not value:
        return []
    return [cc for cc, pat in ZIP_PATTERNS.items()
            if re.fullmatch(pat, value, re.IGNORECASE)]

