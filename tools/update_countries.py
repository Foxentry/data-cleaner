"""
Regenerate `foxentry/countries.py`.

MAINTAINER TOOL - not part of the application and not shipped in the build. It runs on a
maintainer's machine, never on a user's: the application must never fetch reference data at
runtime, so the generated module is committed to the repository and baked into the binary.

    pip install phonenumbers Babel
    git clone https://github.com/Foxentry/OAS ../OAS

    python tools/update_countries.py --oas ../OAS            # rewrite foxentry/countries.py
    python tools/update_countries.py --oas ../OAS --check    # verify it is up to date (CI)

The output is deterministic: no timestamps, everything sorted. Running it twice on the same
inputs produces the same bytes, so `--check` is a reliable drift test and anyone can
reproduce the committed module from its stated sources.

Where the data comes from
-------------------------
* Service coverage - the `dataSource` defaults in the Foxentry OpenAPI specification
  (github.com/Foxentry/OAS). The live source behind those defaults is
  `/projects/v1/service/{service}/enabled-countries`, which the OAS repository syncs itself.
* Calling codes and their primary country - ITU-T E.164, via `phonenumbers`. Non-geographic
  codes (+800 toll-free, +870 Inmarsat, ...) are skipped: they belong to no country and would
  only produce false detections.
* Country names, English and Czech - CLDR, via `Babel`.

Curated below, because no machine-readable source for them is worth a dependency:
postal-code shapes, company legal-form suffixes and neighbouring countries. They are data,
not code - change them here, then regenerate.
"""

